"""Disposable CPU volume metadata; never a real-host GPU ownership proof."""

import os
import subprocess
import tempfile
import unittest
import uuid

from search.operations.deployment import gpu_ownership as ownership
from search.operations.deployment.source_bundle import NGINX_BASE


@unittest.skipUnless(
    os.environ.get("DEPOSITAR_TEST_GPU_LOCAL_VOLUME_RUNTIME") == "1",
    "explicit isolated CPU Docker opt-in required",
)
class LocalVolumeMetadataRuntimeTests(unittest.TestCase):
    def command(self, argv):
        self.commands.append(argv)
        result = ownership.bounded_runner(
            argv, timeout=15, max_bytes=ownership.MAX_OUTPUT_BYTES
        )
        self.assertEqual(
            result.returncode, 0, "disposable Docker metadata command failed"
        )
        return result.stdout

    def docker(self, *arguments):
        return self.command([*ownership.DOCKER_PREFIX, *arguments])

    def cleanup(self):
        # These identifiers are generated/returned by this fixture only.
        failures = []

        def remove(*arguments):
            try:
                result = subprocess.run(
                    [*ownership.DOCKER_PREFIX, *arguments],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    timeout=15,
                )
                if result.returncode:
                    failures.append(" ".join(arguments))
            except (OSError, subprocess.SubprocessError):
                failures.append(" ".join(arguments))

        # A lost run response can leave a created container without a returned
        # ID. Its unique name is generated by this fixture before any mutation.
        identifier = self.container_id or self.volume_name
        remove("stop", "--time", "1", identifier)
        remove("rm", identifier)
        remove("volume", "rm", self.volume_name)
        self.assertEqual(
            failures, [], "owned fixture cleanup failed: " + "; ".join(failures)
        )

    def test_real_local_volume_metadata_and_container_shape_without_gpu_probe(self):
        self.commands = []
        self.container_id = None
        self.volume_name = "depositar-local-volume-fixture-" + uuid.uuid4().hex
        self.addCleanup(self.cleanup)
        self.docker("image", "inspect", "--format", "{{.Id}}", NGINX_BASE)
        self.docker("volume", "create", "--driver", "local", self.volume_name)
        self.container_id = self.docker(
            "run",
            "--detach",
            "--name",
            self.volume_name,
            "--network",
            "none",
            "--runtime",
            "runc",
            "--read-only",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges:true",
            "--pids-limit",
            "16",
            "--memory",
            "64m",
            "--cpus",
            "0.5",
            "--env",
            "NVIDIA_VISIBLE_DEVICES=void",
            "--mount",
            "type=volume,source="
            + self.volume_name
            + ",target=/fixture-data,volume-nocopy",
            "--entrypoint",
            "/bin/sh",
            NGINX_BASE,
            "-c",
            "exec sleep 120",
        ).strip()
        row = ownership._inspect(self.command, self.container_id)
        ownership._container(row)  # Shape only; does not grant volume authority.
        root = ownership._strict_json(
            self.docker("info", "--format", "{{json .DockerRootDir}}")
        )
        before = ownership._collect_local_volumes([row], root, self.command)
        self.assertEqual(len(before), 1)
        self.assertEqual(before[0].name, self.volume_name)
        with self.assertRaisesRegex(
            ownership.GPUOwnershipError, "volume_evidence_invalid"
        ):
            ownership._containers([row], {}, {}, frozenset())
        self.assertEqual(
            set(ownership._containers([row], {}, {}, frozenset(), before)),
            {self.container_id},
        )
        after = ownership._collect_local_volumes([row], root, self.command)
        self.assertEqual(before, after)
        options_name = self.volume_name + "-options"
        with tempfile.TemporaryDirectory(
            prefix="depositar-local-volume-options-"
        ) as directory:
            try:
                self.docker(
                    "volume",
                    "create",
                    "--driver",
                    "local",
                    "--opt",
                    "type=none",
                    "--opt",
                    "o=bind",
                    "--opt",
                    "device=" + directory,
                    options_name,
                )
                # Actual daemon metadata only: no device/bind-options container
                # is started, and this row is never presented as runtime proof.
                declaration = {"Mounts": [{"Type": "volume", "Name": options_name}]}
                with self.assertRaisesRegex(
                    ownership.GPUOwnershipError, "volume_metadata_invalid"
                ):
                    ownership._collect_local_volumes([declaration], root, self.command)
            finally:
                self.docker("volume", "rm", options_name)
        self.assertEqual(row["HostConfig"]["DeviceRequests"], [])
        self.assertTrue(
            all(command[0] in {"docker", "python3"} for command in self.commands)
        )


if __name__ == "__main__":
    unittest.main()
